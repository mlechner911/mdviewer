#!/usr/bin/env python3
"""Regenerate mlcext/glyphs_gen.go from the fonts mlcdoc embeds.

Usage: scripts/glyphs-gen.py <mlcmd2pdf checkout> <mlcdoc version>

Reads the code points of the fonts in mlcmd2pdf's text font list (Liberation
Sans, DejaVu Sans, Twemoji Flags, Noto Emoji) with fc-query and writes their
merged ranges. Run it when mlcdoc changes its fonts, then go test ./mlcext.
"""

import subprocess
import sys
from pathlib import Path

FONTS = [
    ("Liberation Sans", "LiberationSans-Regular.ttf"),
    ("DejaVu Sans", "DejaVuSans.ttf"),
    ("Twemoji Flags", "TwemojiFlags.ttf"),
    ("Noto Emoji", "NotoEmoji-Regular.ttf"),
]


def charset(path: Path) -> list[tuple[int, int]]:
    out = subprocess.run(
        ["fc-query", "--format", "%{charset}", str(path)],
        check=True, capture_output=True, text=True,
    ).stdout
    ranges = []
    for part in out.split():
        lo, _, hi = part.partition("-")
        ranges.append((int(lo, 16), int(hi or lo, 16)))
    return ranges


def merge(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    merged: list[list[int]] = []
    for lo, hi in sorted(ranges):
        if merged and lo <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], hi)
        else:
            merged.append([lo, hi])
    return [(lo, hi) for lo, hi in merged]


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    fonts = Path(sys.argv[1]) / "assets" / "fonts"
    ranges = merge([r for _, f in FONTS for r in charset(fonts / f)])
    names = ", ".join(n for n, _ in FONTS)
    cells = [f"{{0x{lo:X}, 0x{hi:X}}}," for lo, hi in ranges]
    rows = ["\t" + " ".join(cells[i:i + 6])[:-1] + "," for i in range(0, len(cells), 6)]
    target = Path(__file__).resolve().parent.parent / "mlcext" / "glyphs_gen.go"
    target.write_text(
        f"// Code generated by scripts/glyphs-gen.py from the fonts mlcdoc {sys.argv[2]} embeds\n"
        f"// (mlcmd2pdf assets/fonts: {names}) with fc-query;\n"
        "// DO NOT EDIT. Regenerate when mlcdoc changes its fonts.\n\n"
        "package mlcext\n\n"
        "// pdfGlyphRanges are the code points the PDF fonts have, merged and sorted.\n"
        "var pdfGlyphRanges = [][2]rune{\n" + "\n".join(rows) + "\n}\n",
        encoding="utf-8",
    )
    print(f"{target}: {len(ranges)} ranges")


if __name__ == "__main__":
    main()
